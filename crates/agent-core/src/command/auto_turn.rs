//! 自驱动预算：**没人看着的时候，这个会话还能自己往下开几轮**（211，决策 35 §二）。
//!
//! 这个文件只做这一件事的读口 + 一条扣账。「什么时候真的开一轮」是运行时的事
//! （`agent_runtime::auto_turn`），core 不驱动任何东西（红线 7）。
//!
//! # 它**不在原子图里**，跟 `epoch` 同一类
//!
//! 这是本文件最要紧的一条。做成 primitive 槽位的话，`/undo` 会连带把花掉的预算
//! **退还**——而那等于交出一条「撤销 → 重跑 → 再撤销」的无限循环，一次真实用户
//! 操作都不需要。要拦住它就得在 undo 的回滚循环里给这一格开一个例外，
//! 而「所有 primitive 都跟着 undo 走」是这套机制最值钱的一句话，不该为一格计数破掉。
//!
//! 所以它跟 [`Session::epoch`] 一样住在图外：
//!
//! | | 加满 | 花掉 | undo |
//! |---|---|---|---|
//! | `epoch` | — | `Txn::bump_epoch` → `commit_as` | 不回滚（只增不减） |
//! | 自驱动预算 | `Txn::mark_refill_auto_turns` → `commit_as` | [`Session::spend_auto_turn`] | 不回滚（钱已经烧掉了） |
//!
//! **判断留在转移表，状态留在图外**：`Idle + UserInput` 那一格就是「真实用户
//! 输入」的定义，不必在别处再造一个判据。
//!
//! # 不落盘的代价：一次崩溃恢复把它归零
//!
//! 如实记下来：恢复出来的会话这一格是 **0**，不是崩溃前那个值，也不是配置的上限
//! （`command/restore.rs` 里显式写死）。**观察不到差别**——恢复**不自动开轮**
//! （211 §3），而下一次真实用户输入本来就会把它加满。0 是保守的那一侧：
//! 万一哪天有人在恢复路径上误调了驱动器，它也一轮都开不起来。
//!
//! # 三道闸量的不是同一件事
//!
//! 别把它跟另外两道混起来（决策 35 §二 点名）：
//!
//! | 闸 | 量什么 | 住哪 |
//! |---|---|---|
//! | `AgentLimits { max_depth, max_children }` | 树有多大 | 会话配置 |
//! | `Slot::MaxTurns` | **一轮里**说几次话 | 原子图 |
//! | 自驱动预算 | **一次用户输入之后**还能自己开几轮 | 会话状态（图外） |
//!
//! 三个数相乘才是「用户按一次回车之后最坏花多少钱」。

use super::session::Session;

impl Session {
    /// 这个会话现在还能自己开几轮。
    ///
    /// 新建的会话是 **0**：一句话都还没人说过，没有任何东西该自己跑起来。
    /// 只有一次真实用户输入（`transitions::user_input`）才把它加满。
    pub fn auto_turn_budget(&self) -> u32 {
        self.auto_turn_budget
    }

    /// 花掉一格，返回**还剩几格**；已经见底就 `None`，一个字节都不改。
    ///
    /// **减在开轮之前**，不是之后：中间崩了的话，已经花掉的那一格不该复活。
    /// 调用方（运行时）拿 `None` 当「停」的信号——留言原地留在收件箱里，
    /// **不丢弃、不报错**（决策 35 §二）。
    ///
    /// 不落 entry：它不是原子图上的状态（见模块文档）。
    pub fn spend_auto_turn(&mut self) -> Option<u32> {
        if self.auto_turn_budget == 0 {
            return None;
        }
        self.auto_turn_budget -= 1;
        Some(self.auto_turn_budget)
    }
}
